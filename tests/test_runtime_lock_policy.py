"""Safe isolated checks for the packaged runtime and reproducible lock format."""
import importlib.util
import os
from pathlib import Path
import subprocess
import sys

import pytest

ROOT = Path(__file__).resolve().parents[1]


def module():
    path = ROOT / "scripts" / "max2tg-preflight.py"
    spec = importlib.util.spec_from_file_location("max2tg_preflight_checks", path)
    preflight = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(preflight)
    return preflight


def test_compiled_runtime_lock_parses_and_is_subset_of_dev_lock():
    preflight = module()
    runtime = preflight.locked_runtime_packages(ROOT / "requirements.lock")
    dev = preflight.locked_runtime_packages(ROOT / "requirements-dev.lock")
    assert len(runtime) >= 15
    assert all(dev[name] == version for name, version in runtime.items())
    assert "pytest" not in runtime
    assert "ruff" not in runtime
    assert "pytest" in dev and "ruff" in dev


def test_runtime_gate_tracks_latest_candidate_python_and_container():
    preflight = module()
    assert preflight.RELEASE_PYTHON == (3, 15, 2)
    assert (ROOT / ".python-version").read_text().strip() == "3.15"
    dockerfile = (ROOT / "Dockerfile").read_text()
    assert "FROM python:3.15.2-slim" in dockerfile
    assert dockerfile.count("FROM python:3.15.2-slim") == 2
    assert "COPY --from=builder /opt/venv /opt/venv" in dockerfile
    assert "pip==26.3" in dockerfile
    builder, runtime = dockerfile.split("FROM python:3.15.2-slim")[-2:]
    assert "build-essential" in builder
    assert "build-essential" not in runtime
    assert "alpine" not in "\n".join(
        line for line in dockerfile.splitlines()
        if line.lstrip().upper().startswith("FROM ")
    )


@pytest.mark.parametrize("bad", ["", "unknown-package\n", "pytest>=9\n",
                               "same-package==1\nsame-package==2\n"])
def test_invalid_runtime_lock_fails_closed(tmp_path, bad):
    p = tmp_path / "requirements.lock"
    p.write_text(bad)
    with pytest.raises(SystemExit):
        module().locked_runtime_packages(p)


def test_pinned_requirements_ignore_uv_comments(tmp_path):
    p = tmp_path / "requirements.lock"
    p.write_text(
        "# generated by uv\n"
        "aiohttp==3.14.5\n"
        "    # via requirements.txt\n"
        "msgpack==1.1.2 # pinned\n"
    )
    assert module().locked_runtime_packages(p) == {
        "aiohttp": "3.14.5",
        "msgpack": "1.1.2",
    }


def test_preflight_is_safe_when_invoked_as_direct_python_script():
    env = dict(os.environ)
    env.pop("PYTHONPATH", None)
    result = subprocess.run(
        [sys.executable, "scripts/max2tg-preflight.py"],
        cwd=ROOT, env=env, capture_output=True, text=True, timeout=12,
    )
    if sys.version_info[:3] == (3, 15, 2):
        assert result.returncode == 0, result.stderr
        assert "runtime preflight OK" in result.stdout
    else:
        assert result.returncode != 0
        assert "Unexpected MAX2TG Python runtime" in result.stderr
